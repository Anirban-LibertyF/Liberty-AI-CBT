// Generates database/seed.sql from the original React source, so the 5 exam
// presets and the demo paper are copied rather than retyped.
//
//   node tools/build-seed.mjs [path/to/App.jsx]
//
// Re-run it only if the question bank in App.jsx changes.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = readFileSync(resolve(process.argv[2] ?? resolve(here, '../../src/App.jsx')), 'utf8');

// Pull the literal array that follows `const NAME = ` up to the closing `];` at column 0.
function extractArray(name) {
  const start = src.indexOf(`const ${name} = [`);
  if (start === -1) throw new Error(`${name} not found`);
  const open = src.indexOf('[', start);
  const end = src.indexOf('\n];', open);
  if (end === -1) throw new Error(`${name} terminator not found`);
  return new Function(`return ${src.slice(open, end + 2)}`)();
}

const presets = extractArray('EXAM_PRESETS');
const questions = extractArray('DEMO_50_QUESTIONS');

const s = (v) =>
  v === null || v === undefined
    ? 'NULL'
    : "'" + String(v).replace(/\\/g, '\\\\').replace(/'/g, "''").replace(/\0/g, '\\0') + "'";

const out = [];
out.push('-- Generated by tools/build-seed.mjs from src/App.jsx. Do not edit by hand.');
out.push('USE cbt_portal;');
out.push('SET NAMES utf8mb4;');
out.push('');

out.push('-- Exam presets');
presets.forEach((p, i) => {
  out.push(
    `INSERT INTO presets (id, name, badge, duration_minutes, positive_marks, negative_marks, default_count, sort_order) VALUES (${s(p.id)}, ${s(p.name)}, ${s(p.badge)}, ${p.durationMinutes}, ${p.positiveMarks}, ${p.negativeMarks}, ${p.defaultCount}, ${i + 1});`
  );
  p.sections.forEach((sec, j) => {
    out.push(
      `INSERT INTO preset_sections (preset_id, position, name, topics, weight) VALUES (${s(p.id)}, ${j + 1}, ${s(sec.name)}, ${s(sec.topics)}, ${sec.weight});`
    );
  });
});

out.push('');
out.push('-- Demo paper');
out.push(
  `INSERT INTO exams (slug, title, source, status, duration_minutes, positive_marks, negative_marks, include_diagrams) VALUES ('demo', 'All-India Competitive CBT Mock', 'demo', 'ready', 60, 2, 0.5, 1);`
);
out.push('SET @demo_exam = LAST_INSERT_ID();');

questions.forEach((q, i) => {
  out.push(
    `INSERT INTO questions (exam_id, position, section, topic, difficulty, question_text, has_diagram, svg_diagram, explanation, correct_option) VALUES (@demo_exam, ${i + 1}, ${s(q.section)}, ${s(q.topic)}, ${s(q.difficulty)}, ${s(q.questionText)}, ${q.hasDiagram ? 1 : 0}, ${s(q.svgDiagram ?? null)}, ${s(q.explanation)}, ${s(q.correctOption)});`
  );
  out.push('SET @q = LAST_INSERT_ID();');
  for (const o of q.options) {
    out.push(`INSERT INTO question_options (question_id, label, option_text) VALUES (@q, ${s(o.id)}, ${s(o.text)});`);
  }
});

writeFileSync(resolve(here, '../database/seed.sql'), out.join('\n') + '\n');
console.log(`seed.sql: ${presets.length} presets, ${questions.length} demo questions`);
